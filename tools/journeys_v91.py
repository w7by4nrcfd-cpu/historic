def spread(j):
    """توزيع موضع الإجابة الصحيحة بين الخيارات الثلاثة، فلا تكون غالبًا الأولى."""
    for k, s in enumerate(j['steps']):
        t = (sum(map(ord, j['id'])) * 31 + k * k * 7 + k * 5 + len(s['q'])) % 3
        right = s['options'][s['answer']]
        rest = [o for i, o in enumerate(s['options']) if i != s['answer']]
        rest.insert(t, right)
        s['options'], s['answer'] = rest, t


